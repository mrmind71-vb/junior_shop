(
SELECT 
VW_FILE6_20.DOC_NO,
VW_FILE6_20.DATE,
FILE6_20H.TOTAL_ITEM,
FILE6_20H.DISCOUNT,
VW_FILE6_20.RATE AS RATE_OLD,
ROUND(VW_FILE6_20.DISCOUNT_RATE * 100,2) AS RATE_NEW,
SUM(VW_FILE6_20.TOTAL * ROUND(VW_FILE6_20.RATE/100,2)) AS OLD_DISCOUNT,
SUM(VW_FILE6_20.TOTAL * ROUND(VW_FILE6_20.RATE/100,2))- FILE6_20H.DISCOUNT AS DIFFER
FROM VW_FILE6_20 INNER JOIN FILE6_20H ON VW_FILE6_20.DOC_NO = FILE6_20H.DOC_NO
AND VW_fILE6_20.DATE >= '2025-12-01'
AND VW_fILE6_20.DATE <= '2025-12-31'
GROUP BY VW_FILE6_20.DOC_NO,VW_FILE6_20.DATE,VW_FILE6_20.DISCOUNT_RATE,FILE6_20H.TOTAL_ITEM,VW_FILE6_20.RATE,FILE6_20H.DISCOUNT
--ORDER BY ABS(ROUND(VW_FILE6_20.RATE/100,2) - ROUND(VW_FILE6_20.DISCOUNT_RATE,2))  DESC
)
