SELECT FILE6_20H.DOC_NO,
SUM(CASE WHEN FILE6_20.PRICE = FILE6_20.PRICE_C THEN FILE6_20.TOTAL ELSE 0  END),
SUM(CASE WHEN FILE6_20.PRICE <> FILE6_20.PRICE_C THEN FILE6_20.TOTAL ELSE 0  END),
FILE6_20H.TOTAL_ITEM,
FILE6_20H.DISCOUNT
FROM FILE6_20H
INNER JOIN FILE6_20 ON FILE6_20H.DOC_NO = FILE6_20.DOC_NO
WHERE FILE6_20H.DISCOUNT > 0
AND FILE6_20H.DOC_DISC IS NOT NULL
GROUP BY FILE6_20H.DOC_NO,FILE6_20H.DISCOUNT,FILE6_20H.TOTAL_ITEM
HAVING 
SUM(CASE WHEN FILE6_20.PRICE = FILE6_20.PRICE_C THEN FILE6_20.TOTAL ELSE 0  END) <> FILE6_20H.TOTAL_ITEM

SELECT FILE6_20H.DOC_NO,
SUM(CASE WHEN FILE6_20.PRICE = FILE6_20.PRICE_C THEN FILE6_20.TOTAL ELSE 0  END) AS TOTAL_ITEM_OFFER,
SUM(CASE WHEN FILE6_20.PRICE <> FILE6_20.PRICE_C THEN FILE6_20.TOTAL ELSE 0  END),
FILE6_20H.TOTAL_ITEM,
FILE6_20H.DISCOUNT
FROM FILE6_20H
INNER JOIN FILE6_20 ON FILE6_20H.DOC_NO = FILE6_20.DOC_NO
WHERE FILE6_20H.DISCOUNT > 0
AND FILE6_20H.DOC_DISC IS NOT NULL
GROUP BY FILE6_20H.DOC_NO,FILE6_20H.DISCOUNT,FILE6_20H.TOTAL_ITEM
HAVING 
SUM(CASE WHEN FILE6_20.PRICE = FILE6_20.PRICE_C THEN FILE6_20.TOTAL ELSE 0  END) <> FILE6_20H.TOTAL_ITEM


SELECT FILE6_20H.DOC_NO,
SUM(CASE WHEN FILE6_20.PRICE = FILE6_20.PRICE_C THEN FILE6_20.TOTAL ELSE 0  END),
SUM(CASE WHEN FILE6_20.PRICE <> FILE6_20.PRICE_C THEN FILE6_20.TOTAL ELSE 0  END),
FILE6_20H.TOTAL_ITEM,
FILE6_20H.DISCOUNT
FROM FILE6_20H
INNER JOIN FILE6_20 ON FILE6_20H.DOC_NO = FILE6_20.DOC_NO
WHERE FILE6_20H.DISCOUNT > 0
AND FILE6_20H.DOC_DISC IS NOT NULL
GROUP BY FILE6_20H.DOC_NO,FILE6_20H.DISCOUNT,FILE6_20H.TOTAL_ITEM
HAVING 
SUM(CASE WHEN FILE6_20.PRICE = FILE6_20.PRICE_C THEN FILE6_20.TOTAL ELSE 0  END) <> FILE6_20H.TOTAL_ITEM


SELECT FILE6_20H.DOC_NO,
CASE WHEN FILE6_20.PRICE = FILE6_20.PRICE_C THEN  FILE6_20H.DOC_DISC ELSE NULL END AS DOC_OFFER,
FILE6_20H.TOTAL_ITEM,
1 AS OFFER_NO,
TB_OFFER.TOTAL_OFFER,
ROUND((FILE6_20H.DISCOUNT/TB_OFFER.TOTAL_OFFER) * 100,2),
FILE6_20.ID
FROM FILE6_20H
INNER JOIN FILE6_20 ON FILE6_20H.DOC_NO = FILE6_20.DOC_NO
LEFT JOIN 
(SELECT FILE6_20.DOC_NO, SUM(TOTAL) AS TOTAL_OFFER FROM FILE6_20 WHERE 
FILE6_20.PRICE = FILE6_20.PRICE_C
GROUP BY FILE6_20.DOC_NO) 
AS TB_OFFER
ON FILE6_20H.DOC_NO = TB_OFFER.DOC_NO	
WHERE FILE6_20H.DISCOUNT > 0
AND FILE6_20H.DOC_DISC IS NOT NULL
AND FILE6_20.PRICE = FILE6_20.PRICE_C


